]);

/// [TileProvider] that never touches the network: every tile is a blank
/// in-memory image, and requested coordinates are recorded.
class FakeTileProvider extends TileProvider {
  final List<TileCoordinates> requested = [];

  /// URLs the real layer would have fetched (proves the template is used).
  final List<String> urls = [];

  @override
  ImageProvider getImage(TileCoordinates coordinates, TileLayer options) {
    requested.add(coordinates);
    urls.add(getTileUrl(coordinates, options));
    return MemoryImage(_blankPng);
  }
}
